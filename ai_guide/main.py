"""FastAPI application for the MarsPath Ask-the-Map guide."""

import os
from typing import Any, Dict, List, Optional

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, validator

from ai_guide.explainer import explain
from ai_guide.parser_fallback import parse_fallback
from ai_guide.parser_llm import parse_question
from ai_guide.planner_client import (
    PlannerError,
    build_route_request,
    call_planner,
    get_sites,
    to_ui_path,
)
from ai_guide.schema import Coordinates, ParsedRequest


class AskPayload(BaseModel):
    """Validated body for POST /ask."""

    question: str = Field(..., min_length=1, max_length=500)
    map_start: Optional[Coordinates] = None

    @validator("question")
    def question_must_not_be_blank(cls, value: str) -> str:
        """Reject whitespace-only questions while preserving user text."""
        if not value.strip():
            raise ValueError("question must not be blank")
        return value


app = FastAPI(title="MarsPath AI Guide")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_methods=["*"],
    allow_headers=["*"],
)


def _model_dict(model: Any) -> Dict[str, Any]:
    """Convert a Pydantic object to a plain response dictionary."""
    if hasattr(model, "model_dump"):
        return model.model_dump()
    return model.dict()


def _response(
    parsed: ParsedRequest,
    status: str,
    path: list,
    planner: Optional[dict],
    explanation: str,
    source: str = "fallback",
    warnings: Optional[List[str]] = None,
) -> dict:
    """Build the common /ask response shape."""
    return {
        "parsed": _model_dict(parsed),
        "route": {"status": status, "path": path, "planner": planner},
        "explanation": explanation,
        "source": source,
        "warnings": warnings or [],
    }


def _error_response(parsed: ParsedRequest, message: str) -> dict:
    """Build a safe, successful-HTTP response for service-side failures."""
    return _response(parsed, "error", [], None, message, "fallback", [])


def _parser_source_for_answer(parser_source: str, explainer_source: str) -> str:
    """Mark the response as LLM sourced only when both stages used the LLM."""
    return "llm" if parser_source == "llm" and explainer_source == "llm" else "fallback"


def _site_explanation(sites_result: dict) -> str:
    """Describe the first planner-ranked base candidate without extra claims."""
    sites = sites_result.get("sites") or []
    position = sites[0].get("position") if sites and isinstance(sites[0], dict) else None
    if isinstance(position, dict) and "row" in position and "col" in position:
        return f"The best base candidate is at row {position['row']}, column {position['col']}."
    if isinstance(position, dict) and "lat" in position and "lon" in position:
        return f"The best base candidate is at latitude {position['lat']}, longitude {position['lon']}."
    return "I could not read a best base position from the site results."


@app.get("/health")
async def health() -> dict:
    """Return service status without exposing credentials."""
    return {
        "status": "ok",
        "llm_provider": os.getenv("LLM_PROVIDER", "none"),
        "use_mock": os.getenv("USE_MOCK", "0").strip() == "1",
    }


@app.post("/ask")
async def ask(payload: AskPayload) -> dict:
    """Parse a Mars navigation question and handle it without leaking errors."""
    parsed = ParsedRequest()
    parser_source = "fallback"
    warnings: List[str] = []

    try:
        llm_provider = os.getenv("LLM_PROVIDER", "none").strip().lower()
        if llm_provider != "none":
            try:
                parsed = await parse_question(payload.question, payload.map_start)
                parser_source = "llm"
            except Exception:
                parsed = parse_fallback(payload.question)
                parser_source = "fallback"
        else:
            parsed = parse_fallback(payload.question)
            parser_source = "fallback"

        if parsed.intent == "unknown":
            parsed = ParsedRequest(intent="unknown")
            return _response(
                parsed,
                "unknown",
                [],
                None,
                "I can only help with Mars navigation: routes, base sites and EVA briefings. "
                "Try asking about a route to ice.",
            )

        if parsed.intent == "briefing":
            return _response(
                parsed,
                "briefing",
                [],
                None,
                "The EVA briefing is generated by the team's briefing page.",
            )

        if parsed.intent == "sites":
            sites_result = await get_sites()
            if sites_result.get("_mock") is True:
                warnings.append("Using sample data, not live planner results.")
            return _response(
                parsed,
                "sites",
                [],
                sites_result,
                _site_explanation(sites_result),
                warnings=warnings,
            )

        if parsed.intent == "route" and parsed.goal_type == "shelter":
            return _response(
                parsed,
                "unsupported",
                [],
                None,
                "Automatic routing currently supports ice only; shelters and lava tubes "
                "cannot be routed automatically.",
            )

        if parsed.intent == "route" and parsed.goal_type == "base_site":
            return _response(
                parsed,
                "unsupported",
                [],
                None,
                "Routing to the best base site is not automatic. I can offer a nearest-ice "
                "route or the base sites list.",
            )

        if parsed.intent != "route":
            return _response(
                parsed,
                "unknown",
                [],
                None,
                "I can only help with Mars navigation: routes, base sites and EVA briefings. "
                "Try asking about a route to ice.",
            )

        if "avoid_radiation" in parsed.unsupported:
            warnings.append(
                "The planner cannot avoid radiation; radiation is a uniform reference value."
            )
        if parsed.battery_pct is not None and parsed.battery_wh is None:
            warnings.append(
                "Battery percentage converted to Wh assuming a 1000 Wh full battery."
            )
        if parsed.goal_type is None:
            warnings.append("No destination was given, so I assumed the nearest ice.")

        request = build_route_request(parsed, payload.map_start)
        result = await call_planner(request)
        if result.get("_mock") is True:
            warnings.append("Using sample data, not live planner results.")
        text, explainer_source = await explain(
            payload.question, parsed, result, warnings
        )
        status = result.get("status", "error")
        path = to_ui_path(result) if status == "ok" else []
        source = _parser_source_for_answer(parser_source, explainer_source)
        return _response(parsed, status, path, result, text, source, warnings)
    except PlannerError as exc:
        return _error_response(parsed, str(exc))
    except Exception:
        return _error_response(
            parsed,
            "Sorry, I could not answer that right now. Please try again.",
        )
